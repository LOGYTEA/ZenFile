/// 第69轮：UI 图标的**设计规格**（黑白线条 / 圆角简约 / 大小统一）。
///
/// 这一轮把每个图标**单独重画**。上一轮的病根不是"尺寸不一致"，而是
/// **根本没有共同的笔画标准** —— 实测同一排五个图标，每行墨迹量是
/// `41 / 69 / 14 / 20 / 33`，粗细在 1px~2px 之间混着：
///
/// * 最小化只有 14 像素 —— 一根孤线飘在半空；
/// * 最大化的方框比旁边的 × 小一圈；
/// * 关闭的圆头叉反而是五个里最"胖"的（33）。
///
/// 看着"不圆角"只是表象，根子是**每个字形各自决定了自己的笔画**。
///
/// # 这套规格的五条硬规矩
///
/// 1. **统一笔画粗细**：`HW` 由成品边长反算，所有字形**一律用它，不乘任何
///    系数**。视觉轻重靠**形状**（实心/空心、长短）表达，不用粗细。
/// 2. **统一外接框**：所有字形画在 `BOX = 4..28`（24 单位）的正方形里，
///    以 `16,16` 为中心。斜线也顶到 4/28 —— 否则 45° 的 × 天生比横线小。
/// 3. **统一端点**：线段一律**圆头**（`round=true`）。方帽端点在 1px 描边下
///    看着"生硬"，与"圆角简约"直接冲突。
/// 4. **统一留白**：图形不碰 32 单位的边。留白是"简约"的一半 —— 贴边的
///    图标看着挤，也显得比旁边的图标大。
/// 5. **间距 > 笔画直径**：多笔画图标（hamburger / viewlist / gear）的相邻
///    笔画之间必须留出大于 `2*HW` 的空隙，否则抗锯齿后粘连成实心块
///    —— 第67轮"更多菜单三条杠粘成一块砖"就是这个病。
pub mod design {
    /// 设计网格边长（内部坐标恒为 0..32）。
    pub const GRID: f32 = 32.0;

    /// 所有字形的**外接框**（正方形，边长 24 单位，中心 16,16）。
    ///
    /// 斜线/箭头也顶到这个框：45° 斜线在 13px 档的外接盒只有 5×5，
    /// 而横线是 7px —— 不顶满就会显得"× 比 — 小一号"。
    ///
    /// 第70轮：字形占画布边长从 50%（8..24）提到 75%（4..28），`Sm` 档 13px
    /// 的字形从 6.5px 变成 9.75px，对齐 QQ 参照的 10px；同时笔画占外接框的
    /// 比例从 25%（顶着纪律上限）降到 17%，细节留白更宽裕。
    pub const BOX_MIN: f32 = 4.0;
    pub const BOX_MAX: f32 = 28.0;
    pub const CENTER: f32 = 16.0;

    /// 笔画半径（`HW` 是半径不是直径）。
    ///
    /// # ⚠️ 第73轮：这条公式改过 —— 之前是错的
    ///
    /// 第70轮写的是 `2.5 * size/13`，注释宣称"随边长缩放才能光学一致"。
    /// **那是反的。** 它确实让笔画随边长变粗，但代价是：
    /// **同一排图标里，越大的图标笔画越粗**。用户截图实测（真窗口像素，
    /// 沿笔画法线切面求覆盖率）：
    ///
    /// ```text
    ///   Min（Sm 13px）  1.53px  ← 标题栏三键
    ///   Close（Sm 13px） 3.30px
    ///   Back（Xl 18px）  3.59px  ← 工具栏导航
    ///   PaneToggle（Lg） 11.76px ← 左侧面板键
    /// ```
    ///
    /// 最小 1.53px、最大 11.76px —— **差 7.7 倍**。这正是"图标大小不一、
    /// 粗细不一"的直接来源，也是用户最不满意的点。
    ///
    /// # 正确的模型：笔画是**物理量**，不随字号缩放
    ///
    /// 参照物是 QQ 参照：标题栏 10px 光带上的笔画恒定 **2px**，
    /// 旁边的导航箭头也是 2px —— **不管字形多大，笔画都是 2px**。
    /// 这也是 Segoe Fluent、Material、Lucide 等所有图标库的统一做法
    /// （Lucide 的 `stroke-width` 就是常量 2，图标尺寸变而笔画不变）。
    ///
    /// 所以这里改成**只认一个物理直径**：`STROKE_PX`，与 `size` 无关。
    /// 换算回 32 单位设计网格时才用 `size` —— 那不是"粗细随字号变"，
    /// 而是"同一根 1.5px 的物理线，在越小的图标上占的比例越大"
    /// （小图必须相对更粗才看得清，这是**物理下限**，不是设计失误）。
    ///
    /// ```text
    ///   Xs 10px: hw=1.25/32 → 直径占框 20.8%
    ///   Sm 13px: hw=1.25/13 → 直径 2.5px @13px
    ///   Xl 18px: hw=1.25/18 → 直径 2.5px @18px，占框 13.9%
    /// ```
    ///
    /// `STROKE_PX = 1.5`：不是 2px。2px 在 10px 的 `Xs` 档
    /// （状态栏那两个视图按钮就是 `Xs`）会让方框的上下边各吃掉 2px、
    /// 只剩 6px 空腔，糊成实心块 —— 第71轮 `Gear` 糊死过一次。
    /// 1.5px 是"所有档位都清晰"和"小档不糊死"之间的交点。
    pub const STROKE_PX: f32 = 1.5;

    pub fn stroke_hw(size: i32) -> f32 {
        // 32 单位设计网格下，1.5 物理像素对应多少设计单位
        (STROKE_PX * GRID / 2.0) / size as f32
    }

    /// 圆角半径。
    ///
    /// 按**图形高度**的 1/8 给（不是固定值）：1/4 就成了胶囊，1/16 在小尺寸
    /// 下又看不出圆角。1/8 是"确实是圆角、但还是矩形"的分界。
    pub fn corner(h: f32, hw: f32) -> f32 {
        (h / 8.0).min(hw * 1.6)
    }

    /// 多笔画图标的行间距。
    ///
    /// **必须按笔画直径算，不能写死数字**：第69轮把描边从 1px 加粗到
    /// 1.6px 之后，原来写死的 `y = [10,16,22]`（间距 6）间隙只剩
    /// `6 - 2*3.3 = -0.6` —— **负的**，三条杠直接粘连成一块砖。
    ///
    /// 公式：`gap = 直径 + 直径`（即 4*hw）—— 保证净空至少等于一个直径，
    /// 抗锯齿之后仍然看得见分开的缝。
    pub fn row_gap(hw: f32) -> f32 {
        // 公式不变（`= 4*hw`，净空恒等于一个直径），但因为第73轮把
        // `stroke_hw` 改成"物理直径恒定"，`hw` 在大档位**变小**，
        // 于是行距自动收窄 —— 这正是要的：18px 的 hamburger
        // 三条杠应该和 13px 的挤得一样紧，而不是撑成一大片。
        4.0 * hw
    }
}
